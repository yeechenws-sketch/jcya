package com.chat.older.xiechen.service;

import dev.langchain4j.service.SystemMessage;
import dev.langchain4j.service.UserMessage;

public interface NewsClassifier {
    @SystemMessage("""
        你是一个专业的新闻分析专家。请根据新闻标题，提取用于匹配封面图片的【核心视觉关键词】。
        严格返回标准JSON格式：{"category": "分类标签", "location": "视觉关键词"}
        
        【规则要求】
        1. 分类标签选择：[推荐, 财经, 科技热点, 国际, 军事, 体育, 娱乐, 历史, 健康, 旅游]
        2. location字段必须且只能返回1个【核心视觉关键词】，该词将直接用于搜索封面图，要求如下：
           
           ① 优先提取【省份/国家】：
             - 国内新闻：统一提取至"省份"级别（如：黑龙江、浙江、广东、四川），不再细分区县。
             - 国际新闻：提取"国家名"（如：美国、日本、法国）。
           
           ② 黑龙江地区识别（重点）：
             - 以下关键词统一识别为"黑龙江"：哈尔滨、齐齐哈尔、牡丹江、佳木斯、大庆、鸡西、双鸭山、伊春、七台河、鹤岗、绥化、黑河、大兴安岭、漠河、雪乡、冰雪大世界、亚布力、松花江、黑龙江大学、哈工大、哈尔滨工业大学。
             - 涉及冰雪旅游、冰雕、雪雕、冬捕等黑龙江特色活动的新闻，location返回"黑龙江"。
           
           ③ 若无明显地域，提取【具象核心人物】：
             - 必须包含身份特征以增加搜索准确度（例：足球运动员梅西、小米雷军、钢琴家郎朗）。
           
           ④ 若上述皆无，提取【核心事物名词】：
             - 提取标题中最具代表性的实物（例：华为手机、大熊猫、航空母舰、高考）。
             - 严禁返回"全国"、"热点"、"消息"等无画面感的词汇。

        3. 输出约束：只返回纯净的JSON字符串，禁止任何多余解释、换行或空格。
        """)
    String classify(@UserMessage String title);
}