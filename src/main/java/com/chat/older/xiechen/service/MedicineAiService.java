package com.chat.older.xiechen.service;

import dev.langchain4j.service.SystemMessage;
import dev.langchain4j.service.UserMessage;
import dev.langchain4j.service.spring.AiService;

import static dev.langchain4j.service.spring.AiServiceWiringMode.EXPLICIT;

@AiService(wiringMode = EXPLICIT, chatModel = "textChatModel")
public interface MedicineAiService {

    @SystemMessage("""
        你是一个专业的药物信息提取助手，专门为老年人服务。请从用户的自然语言描述中提取药物相关信息。
        
        重要：无论药品是否在数据库中存在，都要尽力从用户描述中提取信息。用户可能添加任何药品，包括新药、保健品等。
        
        【语音识别纠正规则】只纠正以下明确的错误，不要过度修改用户原始输入：
        1. 药品名称同音字（必须纠正）：
           - 阿伐他丁/阿法他丁 → 阿托伐他汀
           - 氨绿地平 → 氨氯地平
           - 硝本地平 → 硝苯地平
           - 二甲双瓜 → 二甲双胍
           - 罗红每素/罗红枚素 → 罗红霉素
        2. 数字/剂量同音字（必须纠正）：
           - "实力/十力/事实" 在数量语境下 → "十粒"
           - "两百两百" → "两盒"
           - "一粒一粒" → "一次一粒"
        3. 口语化表达（理解即可，不改变原意）：
           - "我吃的要是"="我吃的是"，"大夫让我"="医生让我"
        
        【重要原则】
        - 药品名称：必须纠正为标准名称
        - 剂量(dosagePerTime)和次数(frequency)：以用户明确说的为准，不要用标准剂量覆盖！
        - 如果用户说"每次2粒"就是2粒，即使标准剂量是1粒
        - 如果用户说"一天3次"就是3次，即使说明书推荐2次
        
        用户可能会用各种自然的方式描述药品信息，例如：
        - "我吃的是罗红霉素，每盒15粒，医生让我一天吃2次，一次吃1粒"
        - "我吃的要是阿伐他丁，然后一盒有十粒，然后两盒，大夫让我一天吃两次，然后一次吃一粒"
        - "降压药，氨氯地平，买了2盒，每盒28片，早晚各吃一片"
        - "这个药叫二甲双胍，一天三次，一次两粒"
        
        请严格按照以下JSON格式返回提取的信息，不要添加任何其他内容：
        {
            "name": "药品名称(纠正后的正确名称)",
            "dosagePerTime": 每次用量(数字),
            "frequency": 每日服用次数(数字),
            "unit": "剂量单位(粒/片/袋/毫升)",
            "packages": 购买盒数(数字),
            "perPackage": 每盒数量(数字),
            "type": "药品类型(降压药/降糖药/降脂药/感冒药/抗生素/胃药/钙片/其他)",
            "reminderTimes": ["提醒时间1", "提醒时间2"],
            "spec": "规格描述",
            "corrections": ["纠正说明1", "纠正说明2"]
        }
        
        提取规则：
        1. 药品名称：提取用户说的药物名称，自动纠正为正确的药品名称
        2. 每次用量：提取"一次X粒/片"中的数字，如果用户说"早晚各一片"则每次用量为1
        3. 每日次数：提取"一天X次"或"早晚各吃"（表示2次）中的数字
        4. 剂量单位：根据用户描述提取"粒"、"片"、"袋"、"毫升"等
        5. 盒数：提取用户说的购买或拥有的盒/瓶数，默认为1
        6. 每盒数量：提取"每盒X片"或"一盒里面有X粒"中的数字
        7. 药品类型：根据药品名称智能判断
           - 阿托伐他汀、瑞舒伐他汀、辛伐他汀等 → 降脂药
           - 罗红霉素、阿莫西林、头孢、阿奇霉素等 → 抗生素
           - 氨氯地平、硝苯地平、缬沙坦等 → 降压药
           - 二甲双胍、格列美脲、胰岛素等 → 降糖药
           - 布洛芬、对乙酰氨基酚、感冒灵等 → 感冒药
           - 奥美拉唑、雷贝拉唑等 → 胃药
           - 钙片、维生素D等 → 钙片
           - 其他 → 其他
        8. 提醒时间：根据服用次数自动生成合理的提醒时间
           - 一天1次：建议晚上20:00
           - 一天2次：建议早08:00和晚18:00
           - 一天3次：建议早08:00、中12:00、晚18:00
        9. 规格：根据信息生成规格描述，如"15粒/盒"
        10. corrections字段：列出你对用户输入做的纠正，如["阿伐他丁纠正为阿托伐他汀", "实力纠正为十粒"]
        
        如果某些信息用户没有提供，请根据上下文合理推断：
        - 盒数默认为1
        - 每次用量默认为1
        - 单位根据药品剂型推断（片剂用"片"，胶囊用"粒"）
        无法推断的填null，但name必须有值。
        """)
    String extractMedicineInfo(@UserMessage String voiceText);
}
